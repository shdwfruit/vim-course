# ---------- = == ----------

equal = drills.command(
    "equal", "=  ==", "re-indent by the language's rules",
    """= re-indents the lines a motion covers. Instead of shifting them by a fixed amount like > and <, it works
    out each line's indentation from the filetype's rules, so it fixes indentation that's random, not just
    one level off. It's always line-wise: == does this line, =j this line and the next, =ip a paragraph
    (often a whole function), =i{ the lines inside a { } block, =% from a brace to its partner, and gg=G
    the whole file. The rules for C and Java know about braces, case labels and continued lines. Python's
    can't know where a block ends: = only indents the line after a colon and pulls back the line after a
    return or continue, so move Python blocks with > and <.""",
    examples=[("==", "re-indent this line"), ("=ip", "re-indent the paragraph"),
              ("=i{", "re-indent inside the braces"), ("=%", "from this brace to its partner"),
              ("gg=G", "re-indent the whole file"), ("=j", "this line and the next")],
)
